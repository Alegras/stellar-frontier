import { chromium } from "@playwright/test";
const browser = await chromium.launch({ channel: "chrome", args: [] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errs = [];
page.on("pageerror", (e) => { errs.push(e.message); console.log("[pageerror]", e.message.slice(0, 300)); });
page.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
await page.goto("http://127.0.0.1:4174/", { waitUntil: "domcontentloaded" });
await page.waitForTimeout(1800);
await page.locator('[data-testid="btn-mode-campaign"]').first().click();
await page.waitForTimeout(2200);
const map = page.locator('[data-testid="political-map"]');
console.log("map", await map.count(), "canvas", await page.locator('[data-testid="political-map-canvas"]').count(), "legend", await page.locator('[data-testid^="political-legend-"]').count());
await page.evaluate(() => window.__SF_GAME__.setSpeed(0));
const before = await page.evaluate(() => window.__SF_GAME__.getState().selectedSystemId);
const box = await page.locator('[data-testid="political-map-canvas"]').boundingBox();
await page.locator('[data-testid="political-map-canvas"]').click({ position: { x: box.width * 0.55, y: box.height * 0.45 } });
await page.waitForTimeout(500);
const after = await page.evaluate(() => window.__SF_GAME__.getState().selectedSystemId);
console.log("selected", before, "->", after);
await page.screenshot({ path: "docs/shots/political-map.png" });
await page.locator('[data-testid="btn-toggle-political-map"]').click();
await page.waitForTimeout(300);
console.log("collapsed canvas", await page.locator('[data-testid="political-map-canvas"]').count());
await page.locator('[data-testid="btn-toggle-political-map"]').click();
await page.waitForTimeout(300);
console.log("expanded canvas", await page.locator('[data-testid="political-map-canvas"]').count());
console.log("errors", errs.length, errs.slice(0, 5).join(" || "));
await browser.close();
