import { chromium } from "@playwright/test";
import { pathToFileURL } from "node:url";
const html = "C:/Users/vawum/AppData/Local/Temp/sf-gift-test/StellarFrontier.html";
const browser = await chromium.launch({ channel: "chrome", args: [] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errs = [];
page.on("pageerror", (e) => errs.push(e.message));
page.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
await page.goto(pathToFileURL(html).href, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(2200);
await page.locator('[data-testid="btn-mode-campaign"]').first().click();
await page.waitForTimeout(2000);
const tick0 = await page.evaluate(() => window.__SF_GAME__.getState().tick);
await page.keyboard.press("F5");
await page.waitForTimeout(1200);
const save = await page.evaluate(() => window.__SF_GAME__.getState().saveStatus);
await page.reload({ waitUntil: "domcontentloaded" });
await page.waitForTimeout(1600);
await page.locator('[data-testid="btn-continue"]').first().click();
await page.waitForTimeout(1500);
const tick1 = await page.evaluate(() => window.__SF_GAME__.getState().tick);
console.log(JSON.stringify({ tick0, save, tick1, errors: errs.length, sample: errs.slice(0, 3) }));
await browser.close();
