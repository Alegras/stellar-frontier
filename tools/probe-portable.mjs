import { chromium } from "@playwright/test";
import { pathToFileURL } from "node:url";
const browser = await chromium.launch({ channel: "chrome", args: [] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errs = [];
page.on("pageerror", (e) => { errs.push("PAGEERROR: " + e.message); console.log("[pageerror]", e.message.slice(0, 300)); });
page.on("console", (m) => { if (m.type() === "error") { errs.push("CONSOLE: " + m.text()); console.log("[console]", m.text().slice(0, 300)); } });
const url = pathToFileURL("N:/AI/stellar-frontier/StellarFrontier.html").href;
console.log("url", url);
await page.goto(url, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(2500);
console.log("title", await page.title(), "menu", await page.locator('[data-testid="main-menu"]').count());
await page.locator('[data-testid="btn-mode-campaign"]').first().click();
await page.waitForTimeout(2500);
const st = await page.evaluate(() => ({ has: !!window.__SF_GAME__?.hasWorld, mode: window.__SF_GAME__?.getState?.().mode, tick: window.__SF_GAME__?.getState?.().tick }));
console.log("state", JSON.stringify(st));
console.log("webgl", await page.evaluate(() => { const c = document.querySelector("canvas"); return !!c && !!(c.getContext("webgl2") || c.getContext("webgl")); }));
await page.evaluate(() => window.__SF_GAME__.setSpeed(5));
await page.waitForTimeout(2500);
console.log("tick after", await page.evaluate(() => window.__SF_GAME__.getState().tick));
await page.keyboard.press("F5");
await page.waitForTimeout(1500);
console.log("saveStatus", await page.evaluate(() => window.__SF_GAME__.getState().saveStatus));
await page.reload({ waitUntil: "domcontentloaded" });
await page.waitForTimeout(2000);
await page.locator('[data-testid="btn-continue"]').first().click().catch(() => {});
await page.waitForTimeout(1500);
console.log("loaded tick", await page.evaluate(() => window.__SF_GAME__?.getState?.().tick ?? null));
await page.screenshot({ path: "docs/shots/portable-file-preview.png" });
console.log("errors", errs.length, errs.slice(0, 5).join(" || "));
await browser.close();
